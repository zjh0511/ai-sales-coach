const HONOR = { 男: '先生', 女: '小姐' };
const SURNAMES = ['陳', '林', '黃', '張', '李', '王', '吳', '劉', '蔡', '楊', '許', '鄭'];

const pick = (arr, seed) => arr[seed % arr.length];

// 由輸入內容算出穩定的 seed（同樣的輸入 → 同樣的人設，可重現）
export function seedOf(str) {
  return Math.abs([...String(str)].reduce((h, c) => (h * 31 + c.charCodeAt(0)) | 0, 7));
}

// 句尾標點會讓組出來的句子變成「…上幼兒園。的處境推測」，嵌入前要先修掉
export function trimTail(s) {
  return String(s || '').trim().replace(/[。，、；！？.,;!?]+$/, '');
}

// 挑原型：先用關鍵詞計分，比對不到才退回通用或年齡帶。
//
// 回傳 { archetype, score, weak }：
//   weak = true 代表「使用者有描述背景，但我們比對不到任何情境」。
//   呼叫端**必須**把這件事講出來，不可以假裝這是針對他的分析。
export function matchArchetype({ background = '', age = '', seed = 0 } = {}) {
  const bg = String(background || '');
  const real = ARCHETYPES.filter(a => !a.generic);

  if (bg.trim()) {
    // 身分／職業關鍵詞 3 分，處境細節 1 分。
    //
    // 為什麼要分權重（實測案例）：「家管，兩個小孩都上小學了」
    // 在等權重下「家管」與「兩個小孩」各得 1 分，同分後用雜湊決定，
    // 結果跑到「雙薪房貸」去了。**職業身分決定這個人是誰，家庭細節只是補充。**
    const hits = (list) => list.reduce((n, k) => n + (bg.includes(k) ? 1 : 0), 0);
    const scored = real
      .map(a => ({ a, score: hits(a.match.s) * 3 + hits(a.match.w) }))
      .filter(x => x.score > 0)
      .sort((x, y) => y.score - x.score);
    if (scored.length) {
      // 同分時用 seed 決定，維持可重現
      const top = scored.filter(x => x.score === scored[0].score);
      const chosen = pick(top, seed).a;

      // 背景裡出現了**兩種不同身分**的情境（例如「公司老闆，同時在照顧失智的父親」）。
      // 挑哪一個都說得過去，所以不要安靜地挑一個——把另一個也講出來，
      // 讓業務員知道兩邊的重點不一樣、兩邊都該問。
      // 判準是「亞軍也命中了至少一個身分關鍵詞」（3 分），不是分數接近而已。
      const runnerUp = scored.find(x => x.a !== chosen && x.score >= 3);
      return {
        archetype: chosen,
        score: scored[0].score,
        weak: false,
        also: runnerUp ? runnerUp.a : null,
      };
    }
    // 有描述但完全比對不到 → 用通用原型，並且要說出來
    return { archetype: GENERIC, score: 0, weak: true };
  }

  // 完全沒有描述：沒有東西可以牴觸，用年齡帶挑一個是合理的猜測
  const n = Number(String(age).match(/\d+/)?.[0]);
  if (Number.isFinite(n)) {
    const inBand = real.filter(a => n >= a.ages[0] && n <= a.ages[1]);
    if (inBand.length) return { archetype: pick(inBand, seed), score: 0, weak: false };
  }
  return { archetype: pick(real, seed), score: 0, weak: false };
}

// 舊介面：只要原型本身
export function pickArchetype(args) { return matchArchetype(args).archetype; }

// 產出與雲端版 personaPrompt 完全相同形狀的 JSON，session.js 因此不需要知道差別。
export function buildPersona({
  mode = 'call', context = 'cold', gender = '', age = '', background = '',
  difficulty = 1, contextNote = '', product = null, seed = null,
} = {}) {
  const s = seed == null
    ? seedOf(`${mode}|${context}|${gender}|${age}|${background}|${difficulty}`)
    : seed;

  const { archetype: a, weak } = matchArchetype({ background, age, seed: s });
  const g = gender === '男' || gender === '女' ? gender : (s % 2 ? '男' : '女');
  const honor = `${pick(SURNAMES, s)}${HONOR[g]}`;
  const ref = pick(['陳大哥', '林姊', '王經理'], s >> 1);
  const me = '小林';

  const ageText = age ? `${age}` : `約 ${Math.round((a.ages[0] + a.ages[1]) / 2)} 歲`;
  // 使用者自己填的背景優先——他打字進去就是想練那個情境，不該被原型蓋掉
  const bg = background?.trim() ? trimTail(background) : a.background;

  const opening = pick(OPENINGS[context] || OPENINGS.cold, s).replace('{ref}', ref)
    + (OPENING_TAIL[difficulty] || '');

  const fill = t => t.replace('{honor}', honor).replace(/\{me\}/g, me).replace(/\{ref\}/g, ref);

  return {
    name: honor,
    public_summary: `${ageText}的${bg}`.slice(0, 30),
    personality: a.personality,
    communication_style: a.style,
    insurance_attitude: a.attitude,
    trust: 0,                       // 實際值由 session.js 依難度區間夾定
    time_pressure: a.pressure,
    // 字串陣列（app.js 直接串字串顯示）
    hidden_needs: a.hidden.map(h => h.text),
    // 程式判定用的關鍵字，同索引對應。雲端版沒有這個欄位，多出來不影響。
    hidden_keywords: a.hidden.map(h => h.keywords),
    objections: a.objections,
    voice_hint: { rate: a.pressure === 'high' ? 1.1 : 1.0, pitch: g === '女' ? 1.05 : 0.95 },
    opening_line: opening,
    scenario: {
      objective: mode === 'call' ? `讓${honor}答應一次見面或下一次通話`
        : mode === 'needs' ? `問出${honor}自己還沒說出口的那個擔心`
        : `把商品的好處連到${honor}真正在意的事情上`,
      success: mode === 'call' ? '對方明確答應一個時間，或同意你再聯絡'
        : mode === 'needs' ? '對方主動講出至少一件他心裡真正在意的事'
        : '對方問到費用、條件或「那我要怎麼做」',
      fail: '對方失去耐心結束對話，或整場只有你在講',
    },
    demo: {
      opening: fill(DEMO_OPEN[context] || DEMO_OPEN.cold),
      key_question: DEMO_Q[mode] || DEMO_Q.call,
      objection_handling: DEMO_OBJ[mode] || DEMO_OBJ.call,
    },
    archetypeId: a.id,
    archetypeWeak: weak,            // 比對不到情境時為 true，畫面應該講出來
    contextNote: contextNote || '',
    productTitle: product?.title || null,
  };
}

// turnSignals 需要 {text, keywords} 形狀；persona 保存的是兩個平行陣列。
// 兩邊都保留，各自拿到自己需要的形狀，畫面不會出現 [object Object]。
export function hiddenWithKeywords(persona) {
  const texts = persona?.hidden_needs || [];
  const kws = persona?.hidden_keywords || [];
  return texts.map((t, i) => ({ text: t, keywords: kws[i] || [] }));
}
