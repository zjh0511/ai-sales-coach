//   **光是產生這份 JSON 就要三到四分鐘**，而且小模型產生長 JSON 的失敗率很高。
//
//   人設的本質是「一份設定資料」，不是需要即時創作的內容。
//   改成程式組裝之後：0 毫秒、100% 成功、離線，而且品質可以審閱。
//
// ⚠ hidden_needs 對外必須是「字串陣列」。
//   app.js:654 是 `('✅ ' + h)` 直接串字串，放物件進去畫面會出現 [object Object]。
//   關鍵字等額外資訊放在 hidden_keywords（同索引對應），
//   由 gateway-local.js 在需要時才合成物件。
//
// ── 每個原型的內容都集中在這裡 ────────────────────────────────────
//
// 2026-08-21 的重構：隱藏需求原本只有 text ＋ keywords，
