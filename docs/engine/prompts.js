// FULL：完整公司名 → ○○人壽。「台灣」「中國」等只在接著「人壽」時才視為公司名。
const BRAND_FULL = /(臺灣|台灣|中國|全球|遠雄|宏泰|保誠|安聯|友邦|三商美邦|南山|國泰|富邦|新光|凱基|元大|台新|安達|保德信|宏利|大都會|第一金|合作金庫|中華郵政)(人壽|產險|保險|金控)/g;
// BARE：單獨出現也一定是保險品牌的字號
const BRAND_BARE = /(國泰|富邦|南山|新光|宏泰|三商美邦|遠雄|保誠|安聯|友邦|法國巴黎|明台|旺旺友聯|新安東京|保德信|AIA|Prudential|Allianz)/g;

export function scrubBrands(s) {
  if (typeof s !== 'string') return s;
  return s.replace(BRAND_FULL, '○○人壽').replace(BRAND_BARE, '○○');
}

// 深層套用到物件裡的所有字串（示範話術通常是巢狀結構）
export function scrubDeep(o) {
  if (typeof o === 'string') return scrubBrands(o);
  if (Array.isArray(o)) return o.map(scrubDeep);
  if (o && typeof o === 'object') {
    for (const k of Object.keys(o)) o[k] = scrubDeep(o[k]);
  }
  return o;
}

