// ── 輸出驗證：角色扮演不得跳出角色 ──────────────────────────────
const BREAK = /(身為|作為).{0,4}(AI|人工智慧|客戶角色)|我是.{0,4}(AI|語言模型|助理|教練)|建議你|你可以嘗試|話術|演練|模擬|練習中|評分|加油/;

export function validateRoleplay(say) {
  if (!say) return null;
  let s = say.replace(/^["「『]|["」』]$/g, '').trim();
  if (BREAK.test(s)) return null;                      // 跳出角色 → 交由呼叫端重試
  if (s.length > 120) {                                 // 過長 → 切到最後一個完整句
    const cut = s.slice(0, 120);
    const i = Math.max(cut.lastIndexOf('。'), cut.lastIndexOf('？'), cut.lastIndexOf('！'));
    s = i > 20 ? cut.slice(0, i + 1) : cut;
  }
  return s;
}
