/** 把模型輸出裡的簡體字換成台灣繁體。非中文內容完全不動。 */
export function toTW(text) {
  if (typeof text !== 'string' || !text) return text;
  let t = text;
  for (const [re, to] of WORDS) t = t.replace(re, to);
  return t.replace(RE, c => MAP.get(c) || c);
}

/** 轉換後還剩下哪些簡體字。用來衡量某個模型「乾不乾淨」，不是給使用者看的。 */
export function simplifiedLeft(text) {
  const m = String(text || '').match(RE);
  return m ? [...new Set(m)].join('') : '';
}
